    vehicle_origin_code not in (3,4)
    or (
      lessor_doc ~ '^([0-9]{11}|[0-9]{14})$'
      and lessor_name is not null
      and monthly_value > 0
      and has_driver is not null
      and cw_contract_code ~ '^CW-[0-9]{6}/[0-9]{2}$'
    )
  ),
  -- v4: datas de locação coerentes quando ambas preenchidas
  constraint chk_lease_dates check (
    lessor_lease_end_date is null
    or lessor_lease_start_date is null
    or lessor_lease_end_date >= lessor_lease_start_date
  )
);
