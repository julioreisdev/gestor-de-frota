    into v_sup_kind, v_sup_name, v_sup_cnpj
    from supplier where id = p_supplier_id;
  if v_sup_name is null then raise exception 'Fornecedor não encontrado'; end if;
  if v_sup_kind = 'posto' then
    raise exception 'Fornecedor cadastrado apenas como Posto não pode receber autorização de manutenção';
  end if;
  if p_estimated_value is null or p_estimated_value <= 0 then
    raise exception 'Valor estimado deve ser maior que zero';
  end if;
  if p_description is null or length(trim(p_description)) < 3 then
    raise exception 'Descrição do serviço é obrigatória (mínimo 3 caracteres)';
  end if;

  -- Limite mensal (soma combustível + manutenção)
  select monthly_authorization_limit into v_user_limit
    from app_user
    where full_name = p_responsible_name and active = true
    limit 1;
  if v_user_limit is not null and v_user_limit > 0 then
    select coalesce((
      select sum(estimated_total) from fueling_authorization
       where responsible_name = p_responsible_name
         and status in ('emitida','utilizada')
         and date_trunc('month', date) = date_trunc('month', p_date)
         and deleted_at is null
    ), 0) + coalesce((
      select sum(estimated_value) from service_authorization
       where responsible_name = p_responsible_name
         and status in ('emitida','utilizada')
         and date_trunc('month', date) = date_trunc('month', p_date)
         and deleted_at is null
    ), 0)
    into v_month_used;
    if v_month_used + p_estimated_value > v_user_limit then
      raise exception 'Limite mensal do responsável excedido: limite R$%, usado R$%, nova R$%',
        v_user_limit, v_month_used, p_estimated_value;
    end if;
  end if;

  v_number := generate_service_authorization_number(p_date);
  v_qr := format(
    E'GERIR FROTA — AUTORIZAÇÃO DE MANUTENÇÃO\n' ||
    E'Nº: %s\n' ||
    E'Data: %s\n' ||
    E'Veículo: %s — %s\n' ||
    E'Categoria: %s\n' ||
    E'Serviço: %s\n' ||
    E'Valor estimado: R$ %s\n' ||
    E'Mecânica: %s (CNPJ %s)\n' ||
    E'Secretaria: %s\n' ||
    E'Responsável: %s\n' ||
    E'Situação: EMITIDA',
    v_number,
    to_char(p_date,'DD/MM/YYYY'),
    v_plate, v_model,
    upper(p_service_kind::text),
    p_description,
    to_char(p_estimated_value, 'FM999990D90'),
    v_sup_name, v_sup_cnpj,
    coalesce(v_dept,'—'),
    p_responsible_name
  );

  insert into service_authorization (
    number, date, vehicle_id, supplier_id, service_kind, description,
    estimated_value, responsible_name, notes,
    vehicle_plate_snapshot, vehicle_model_snapshot,
    department_acronym_snapshot, supplier_trade_name_snapshot,
    qr_payload, created_by
  ) values (
    v_number, p_date, p_vehicle_id, p_supplier_id, p_service_kind, p_description,
    p_estimated_value, p_responsible_name, p_notes,
    v_plate, v_model, v_dept, v_sup_name,
    v_qr, auth.uid()
  ) returning id into v_auth_id;
  return v_auth_id;
end;
$$;
